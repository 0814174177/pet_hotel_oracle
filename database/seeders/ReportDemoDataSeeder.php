                    'total_amount' => $grandTotal,
                    'special_notes' => 'Dữ liệu báo cáo tháng 4-5/2026 tại chi nhánh ' . $branchName[$case['branch_id']] . '.',
                    'created_at' => $createdAt,
                    'updated_at' => $paidAt ?? $createdAt,
                ];

                $bookingRooms[] = [
                    'booking_room_id' => $currentBookingRoomId,
                    'booking_id' => $currentBookingId,
                    'room_id' => $case['room_id'],
                    'assigned_at' => $createdAt->copy()->addMinutes(30),
                    'notes' => 'Gán phòng có sẵn ' . $room['name'] . ' cho dữ liệu báo cáo.',
                    'created_at' => $createdAt,
                    'updated_at' => $createdAt,
                ];

                $bookingRoomPets[] = [
                    'booking_room_pet_id' => $bookingRoomPetId++,
                    'booking_room_id' => $currentBookingRoomId,
                    'pet_id' => $case['pet_id'],
                    'notes' => 'Gắn thú cưng mới vào phòng lưu trú.',
                    'created_at' => $createdAt,
                    'updated_at' => $createdAt,
                ];

                $orders[] = [
                    'order_id' => $currentOrderId,
                    'customer_id' => $case['customer_id'],
                    'branch_id' => $case['branch_id'],
                    'booking_id' => $currentBookingId,
                    'created_by_emp' => $managerByBranch[$case['branch_id']],
                    'created_by_user_id' => $userByBranch[$case['branch_id']],
                    'coupon_id' => $case['coupon_id'],
                    'payment_method' => $case['payment_method'],
                    'status' => $case['order_status'],
                    'subtotal' => $subtotal,
                    'discount_amount' => $discount,
                    'grand_total' => $grandTotal,
                    'paid_at' => $paidAt,
                    'created_at' => $createdAt,
                    'updated_at' => $paidAt ?? $createdAt,
                    'customer_name' => $case['customer_name'],
                    'customer_phone' => $case['customer_phone'],
                    'customer_email' => $case['customer_email'],
                ];

                $orderDetails[] = [
                    'order_detail_id' => $orderDetailId++,
                    'order_id' => $currentOrderId,
                    'booking_room_id' => $currentBookingRoomId,
                    'booking_service_pet_id' => null,
                    'title' => $room['type'] . ' ' . $room['name'] . ' (' . $case['nights'] . ' đêm)',
                    'quantity' => $case['nights'],
                    'unit_price' => $room['price'],
                    'line_total' => $roomLine,
                    'created_at' => $createdAt,
                    'updated_at' => $createdAt,
                ];

                $orderDetails[] = [
                    'order_detail_id' => $orderDetailId++,
                    'order_id' => $currentOrderId,
                    'booking_room_id' => $currentBookingRoomId,
                    'booking_service_pet_id' => null,
                    'title' => 'Suất ăn và nước uống theo ngày cho ' . $case['pet_name'],
                    'quantity' => $case['nights'],
                    'unit_price' => $case['food_unit'],
                    'line_total' => $foodLine,
                    'created_at' => $createdAt,
                    'updated_at' => $createdAt,
                ];

                $orderDetails[] = [
                    'order_detail_id' => $orderDetailId++,
                    'order_id' => $currentOrderId,
                    'booking_room_id' => $currentBookingRoomId,
                    'booking_service_pet_id' => null,
                    'title' => 'Phí vệ sinh, khử khuẩn và chăm sóc phòng lưu trú',
                    'quantity' => 1,
                    'unit_price' => $case['care_unit'],
                    'line_total' => $careLine,
                    'created_at' => $createdAt,
                    'updated_at' => $createdAt,
                ];

                if ($case['weekend_fee'] > 0) {
                    $orderDetails[] = [
                        'order_detail_id' => $orderDetailId++,
                        'order_id' => $currentOrderId,
                        'booking_room_id' => $currentBookingRoomId,
                        'booking_service_pet_id' => null,
                        'title' => 'Phụ thu cuối tuần',
                        'quantity' => 1,
                        'unit_price' => $case['weekend_fee'],
                        'line_total' => $case['weekend_fee'],
                        'created_at' => $createdAt,
                        'updated_at' => $createdAt,
                    ];
                }

                if ($case['late_fee'] > 0) {
                    $orderDetails[] = [
                        'order_detail_id' => $orderDetailId++,
                        'order_id' => $currentOrderId,
                        'booking_room_id' => $currentBookingRoomId,
                        'booking_service_pet_id' => null,
                        'title' => 'Phí chăm sóc ngoài giờ',
                        'quantity' => 1,
                        'unit_price' => $case['late_fee'],
                        'line_total' => $case['late_fee'],
                        'created_at' => $createdAt,
                        'updated_at' => $createdAt,
                    ];
                }

                if ($case['coupon_id'] !== null && $case['order_status'] !== 'CANCELLED') {
