                    ];
                } elseif ($case['order_status'] === 'PARTIAL') {
                    $partialAmount = (int) floor(($grandTotal * 0.6) / 1000) * 1000;
                    $payments[] = [
                        'payment_id' => $paymentId++,
                        'order_id' => $currentOrderId,
                        'payment_method' => $case['payment_method'],
                        'provider' => $providerByMethod[$case['payment_method']],
                        'amount' => max(50000, min($partialAmount, $grandTotal - 10000)),
