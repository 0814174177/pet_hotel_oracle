                $paidAt = in_array($case['order_status'], ['COMPLETED', 'PAID'], true)
                    ? $checkout->copy()->subHours(1 + ($index % 5))
                    : null;

                $actualCheckin = in_array($case['booking_status'], ['COMPLETED'], true)
                    ? $checkin->copy()->subMinutes(5 + ($index % 20))
                    : null;

                $actualCheckout = in_array($case['booking_status'], ['COMPLETED'], true)
                    ? $checkout->copy()->subMinutes(5 + ($index % 30))
                    : null;

                $bookings[] = [
                    'booking_id' => $currentBookingId,
                    'customer_id' => $case['customer_id'],
                    'branch_id' => $case['branch_id'],
                    'checkin_expected_at' => $checkin,
                    'checkout_expected_at' => $checkout,
                    'checkin_actual_at' => $actualCheckin,
                    'checkout_actual_at' => $actualCheckout,
