                        'note' => 'Thanh toán một phần, còn công nợ khách hàng.',
                        'created_at' => $createdAt,
                        'updated_at' => $createdAt->copy()->addHours(2),
                    ];
                } elseif ($case['order_status'] === 'PENDING') {
                    $payments[] = [
                        'payment_id' => $paymentId++,
                        'order_id' => $currentOrderId,
                        'payment_method' => $case['payment_method'],
                        'provider' => $providerByMethod[$case['payment_method']],
                        'amount' => min(100000, max(50000, (int) floor($grandTotal * 0.2 / 1000) * 1000)),
                        'status' => 'PENDING',
                        'paid_at' => null,
                        'note' => 'Khách đã tạo yêu cầu thanh toán, hệ thống chưa xác nhận.',
                        'created_at' => $createdAt,
                        'updated_at' => $createdAt,
                    ];
                }
            }
        }

        foreach (array_chunk($customers, 200) as $chunk) {
            DB::table('customer')->insert($chunk);
        }
        foreach (array_chunk($pets, 200) as $chunk) {
            DB::table('pet')->insert($chunk);
        }
        foreach (array_chunk($bookings, 200) as $chunk) {
            DB::table('booking')->insert($chunk);
        }
        foreach (array_chunk($bookingRooms, 200) as $chunk) {
            DB::table('booking_room')->insert($chunk);
        }
        foreach (array_chunk($bookingRoomPets, 200) as $chunk) {
            DB::table('booking_room_pet')->insert($chunk);
        }
        foreach (array_chunk($orders, 200) as $chunk) {
            DB::table('orders')->insert($chunk);
        }
        foreach (array_chunk($orderDetails, 200) as $chunk) {
            DB::table('order_details')->insert($chunk);
        }
        foreach (array_chunk($couponLogs, 200) as $chunk) {
            DB::table('booking_coupon_log')->insert($chunk);
        }
        foreach (array_chunk($payments, 200) as $chunk) {
            DB::table('payments')->insert($chunk);
        }
    }
