                        'notes' => 'Áp dụng coupon có sẵn, giảm ' . number_format($discount, 0, ',', '.') . 'đ.',
                        'created_at' => $createdAt,
                        'updated_at' => $createdAt,
                    ];
                }

                if ($case['order_status'] === 'COMPLETED' || $case['order_status'] === 'PAID') {
                    $payments[] = [
                        'payment_id' => $paymentId++,
                        'order_id' => $currentOrderId,
                        'payment_method' => $case['payment_method'],
                        'provider' => $providerByMethod[$case['payment_method']],
